static void video_put_pixel(int x, int y, u8 color) {
    u8 *dst;

    if (x < 0 || y < 0 || x >= (int)g_width || y >= (int)g_height) {
        return;
    }

    dst = g_framebuffer + (usize)y * g_pitch + (usize)x * g_bytes_per_pixel;
    if (g_bpp == 8) {
        dst[0] = color;
    } else {
        u32 value = g_palette32[color & 0x0f];

        dst[0] = (u8)(value & 0xffu);
        dst[1] = (u8)((value >> 8) & 0xffu);
        dst[2] = (u8)((value >> 16) & 0xffu);
        if (g_bytes_per_pixel == 4) {
            dst[3] = 0x00;
        }
    }
}

void video_init(void) {
    g_video_is_ready = 0;
    g_bpp = g_boot_info.framebuffer_bpp;
    g_bytes_per_pixel = (g_bpp + 7u) / 8u;
    g_font_data = &g_font8x8[0][0];
    g_font_height = 8;
    g_text_scale = 1;
    if ((g_bpp != 8 && g_bpp != 24 && g_bpp != 32) || g_boot_info.framebuffer_addr == 0) {
        return;
    }

    g_framebuffer = (u8 *)(usize)g_boot_info.framebuffer_addr;
    g_width = g_boot_info.framebuffer_width;
    g_height = g_boot_info.framebuffer_height;
    g_pitch = g_boot_info.framebuffer_pitch;
    if (!g_framebuffer || g_width == 0 || g_height == 0 || g_pitch < g_width * g_bytes_per_pixel) {
        g_framebuffer = NULL;
        g_width = 0;
        g_height = 0;
        g_pitch = 0;
        g_bpp = 0;
        g_bytes_per_pixel = 0;
        return;
    }

    if (g_boot_info.font_addr != 0 && g_boot_info.font_height >= 8 && g_boot_info.font_height <= 16) {
        g_font_data = (const u8 *)(usize)g_boot_info.font_addr;
        g_font_height = (int)g_boot_info.font_height;
    }

    if (g_font_height >= 16) {
        if (g_width >= 800 && g_height >= 600) {
            g_text_scale = 2;
        }
    } else if (g_bpp >= 24 && g_width >= 1600 && g_height >= 900) {
        g_text_scale = 4;
    } else if (g_bpp >= 24 && g_width >= 1024 && g_height >= 768) {
        g_text_scale = 3;
    } else if (g_bpp >= 24 && g_width >= 800 && g_height >= 600) {
        g_text_scale = 2;
    }

    g_video_is_ready = 1;
    if (g_bpp == 8) {
        video_load_palette();
    }
}

void video_clear(u8 color) {
    if (!g_video_is_ready) {
        return;
    }

    for (u32 y = 0; y < g_height; ++y) {
        if (g_bpp == 8) {
            memset(g_framebuffer + (usize)y * g_pitch, color, g_width);
        } else {
            for (u32 x = 0; x < g_width; ++x) {
                video_put_pixel((int)x, (int)y, color);
            }
        }
    }
}

void video_fill_rect(int x, int y, int w, int h, u8 color) {
    if (!g_video_is_ready || w <= 0 || h <= 0) {
        return;
    }
    if (x >= (int)g_width || y >= (int)g_height || x + w <= 0 || y + h <= 0) {
        return;
    }

    if (x < 0) {
        w += x;
        x = 0;
    }
    if (y < 0) {
        h += y;
        y = 0;
    }
    if (x + w > (int)g_width) {
        w = (int)g_width - x;
    }
    if (y + h > (int)g_height) {
        h = (int)g_height - y;
    }

    for (int row = 0; row < h; ++row) {
        if (g_bpp == 8) {
            memset(g_framebuffer + (usize)(y + row) * g_pitch + (usize)x, color, (usize)w);
        } else {
            for (int col = 0; col < w; ++col) {
                video_put_pixel(x + col, y + row, color);
            }
        }
    }
}

static void video_draw_char_internal(int x, int y, int scale, u8 fg, u8 bg, char ch) {
    const u8 *glyph_bits;
    u8 glyph = (u8)ch;

    if (!g_video_is_ready) {
        return;
    }
    if (glyph >= 128) {
        glyph = '?';
    }

    if (scale < 1) {
        scale = 1;
    }

    glyph_bits = g_font_data + (usize)glyph * (usize)g_font_height;
    video_fill_rect(x, y, 8 * scale, g_font_height * scale, bg);
    for (int row = 0; row < g_font_height; ++row) {
        u8 bits = glyph_bits[row];
        for (int col = 0; col < 8; ++col) {
            if ((bits & (u8)(0x80u >> col)) != 0) {
                for (int sy = 0; sy < scale; ++sy) {
                    for (int sx = 0; sx < scale; ++sx) {
                        video_put_pixel(x + col * scale + sx, y + row * scale + sy, fg);
                    }
                }
            }
        }
    }
}

void video_draw_char(int x, int y, u8 fg, u8 bg, char ch) {
    video_draw_char_internal(x, y, 1, fg, bg, ch);
}

void video_draw_char_scaled(int x, int y, int scale, u8 fg, u8 bg, char ch) {
    video_draw_char_internal(x, y, scale, fg, bg, ch);
}

void video_draw_text(int x, int y, u8 fg, u8 bg, const char *text) {
    if (!g_video_is_ready || !text) {
        return;
    }

    for (usize i = 0; text[i]; ++i) {
        video_draw_char(x + (int)i * 8, y, fg, bg, text[i]);
    }
}
